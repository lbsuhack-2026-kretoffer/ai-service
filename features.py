# Доли категорий буфета для СИНТЕТИЧЕСКОЙ генерации данных.
# Жёстких коэффициентов нет — каждая категория независима, сумма не обязана
# быть равна 1.0. Используются только при генерации fallback-данных,
# не при инференсе. Коэффициенты берутся из env BUFFET_RATIO_<КАТЕГОРИЯ> 
# (например BUFFET_RATIO_HOT=0.42), иначе — равномерное распределение.
# ---------------------------------------------------------------------------

def buffet_ratio_for(category: str, age_group: str = "middle") -> float:
    """Доля категории для заданной возрастной группы (синтетика/фолбэк).

    Возрастная группа не влияет на коэффициент (паттерны потребления узнаются
    моделью из реальных данных, а не задаются жёстко). Коэффициент берётся из
    переменной окружения BUFFET_RATIO_<КАТЕГОРИЯ_В_ВЕРХНЕМ_РЕГИСТРЕ>, иначе
    равномерное распределение 1.0 / число категорий.
    """
    import os as _os
    env_key = f"BUFFET_RATIO_{category.upper()}"
    val = _os.getenv(env_key)
    if val is not None:
        try:
            return float(val)
        except ValueError:
            pass
    return 1.0 / len(BUFFET_CATEGORIES) if BUFFET_CATEGORIES else 0.25


# ---------------------------------------------------------------------------
# Календарь каникул и праздников (ISO даты)
# Можно расширять из переменной окружения HOLIDAY_CALENDAR (JSON со списком дат)
# ---------------------------------------------------------------------------
_PRESET_HOLIDAYS = {
    "2026-10-30",  # предпраздничный
    "2026-10-31",  # каникулы
    "2026-11-01",
    "2026-12-18",  # предпраздничный
    "2026-12-19",  # каникулы
    "2026-12-20",
}


def get_holiday_calendar() -> set[str]:
    """Возвращает множество дат каникул/праздников (ISO строки).

    Источник: переменная окружения HOLIDAY_CALENDAR (JSON-массив дат),
    дополненная встроенным набором.
    """
    dates = set(_PRESET_HOLIDAYS)
    env_val = _os.getenv("HOLIDAY_CALENDAR")
    if env_val:
        try:
            extra = _json.loads(env_val)
            if isinstance(extra, list):
                dates.update(extra)
        except _json.JSONDecodeError:
            pass
    return dates
